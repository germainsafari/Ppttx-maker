# ============================================================== low-level helpers
def I(x: float) -> Emu:  # noqa: E743 - inches shorthand
    return Inches(x)


def set_bg(slide, color: str):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = rgb(color)


def text_box(shapes, x, y, w, h, text="", size=14, color=BLACK, bold=False, font=None, align=PP_ALIGN.LEFT,
             anchor=MSO_ANCHOR.TOP, spacing=None, caps=False, line_spacing=None, wrap=True):
    tb = shapes.add_textbox(I(x), I(y), I(w), I(h))
    tf = tb.text_frame
    tf.word_wrap = wrap
    tf.vertical_anchor = anchor
    for side in ("margin_left", "margin_right", "margin_top", "margin_bottom"):
        setattr(tf, side, 0)
    paragraphs = text if isinstance(text, list) else [text]
    for i, t in enumerate(paragraphs):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        if line_spacing:
            p.line_spacing = line_spacing
        _run(p, t.upper() if caps else t, size, color, bold, font, spacing)
    return tb


def _run(p, text, size, color, bold=False, font=None, spacing=None):
    r = p.add_run()
    r.text = text
    f = r.font
    f.size = Pt(size)
    f.bold = bold
    f.color.rgb = rgb(color)
    if font:
        f.name = font
    if spacing:
        r._r.get_or_add_rPr().set("spc", str(int(spacing)))
    return r


def rect(shapes, x, y, w, h, fill=CREAM_LIGHT, line=None, rounded=0.06, shape=None):
    shp = shapes.add_shape(shape or (MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE),
                           I(x), I(y), I(w), I(h))
    if rounded and shape is None:
        shp.adjustments[0] = rounded
    if fill:
        shp.fill.solid()
        shp.fill.fore_color.rgb = rgb(fill)
    else:
        shp.fill.background()
    if line:
        shp.line.color.rgb = rgb(line)
        shp.line.width = Pt(1)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    if shp.has_text_frame:
        shp.text_frame.text = ""
    return shp


def line(shapes, x1, y1, x2, y2, color=BLACK, width=1.0, dash=False):
    ln = shapes.add_connector(MSO_CONNECTOR.STRAIGHT, I(x1), I(y1), I(x2), I(y2))
    ln.line.color.rgb = rgb(color)
    ln.line.width = Pt(width)
    if dash:
        ln.line.dash_style = 4  # dash
    return ln


def picture(shapes, key_or_path, x, y, w=None, h=None, rot=0, flip_h=False):
    path = key_or_path if isinstance(key_or_path, (Path, io.BytesIO)) else asset(key_or_path)
    if path is None:
        return None
    pic = shapes.add_picture(path if isinstance(path, io.BytesIO) else str(path), I(x), I(y),
                             I(w) if w else None, I(h) if h else None)
    if rot:
        pic.rotation = rot
    if flip_h:
        pic._element.spPr.find(qn("a:xfrm")).set("flipH", "1")
    return pic


def orbit(shapes, x, y, w, h, rot, flip_h=False, width=0.75):
    o = shapes.add_shape(MSO_SHAPE.OVAL, I(x), I(y), I(w), I(h))
    o.fill.background()
    o.line.color.rgb = rgb(BLACK)
    o.line.width = Pt(width)
    o.rotation = rot
    o.shadow.inherit = False
    if flip_h:
        o._element.spPr.find(qn("a:xfrm")).set("flipH", "1")
    return o


def set_title(slide, title: str, size: float | None = None, underscore=True, color=BLACK):
    ph = next((p for p in slide.placeholders if p.placeholder_format.idx == 0), None)
    if ph is None:
        return None
    tf = ph.text_frame
    tf.text = ""
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = title.rstrip("_ ")
    r.font.color.rgb = rgb(color)
    if size:
        r.font.size = Pt(size)
    if underscore:
        u = p.add_run()
        u.text = "_"
        u.font.color.rgb = rgb(CORAL)
        if size:
            u.font.size = Pt(size)
    return ph


GENERIC_LABEL = re.compile(r"^\s*((step|phase|stage)\s*)?\d{0,2}\s*$", re.I)


def _tag_score(key: str, text: str) -> int:
    words = set(re.findall(r"[a-z]+", text.lower()))
    return len(words & set(catalog()[key]["tags"].split()))


def distinct_icons(wanted: list[tuple[str, str]]) -> list[str]:
    """Keep the model's icon choices but never repeat one on a slide; replacements are matched by tags."""
    pool = [k.split("/", 1)[1] for k, v in catalog().items() if v["kind"] == "icon"]
    used, out = set(), []
    for icon, text in wanted:
        if icon not in pool or icon in used:
            free = [p for p in pool if p not in used] or pool
            icon = max(free, key=lambda p: _tag_score(f"icon/{p}", text))
        used.add(icon)
        out.append(icon)
    return out


def pick_illustration(text: str) -> str:
    """Choose the brand illustration whose catalog tags best match the slide text."""
    words = set(re.findall(r"[a-z]+", text.lower()))
    best, best_score = "documents", 0
    for key, item in catalog().items():
        if item["kind"] != "illustration" or key.endswith("logo_a"):
            continue
        score = len(words & set(item["tags"].split()))
        if score > best_score:
            best, best_score = key.split("/", 1)[1], score
    return best


def remove_empty_placeholders(slide):
    for ph in list(slide.placeholders):
        if ph.has_text_frame and not ph.text_frame.text.strip():
            ph._element.getparent().remove(ph._element)


def set_notes(slide, notes: str):
    if notes:
        slide.notes_slide.notes_text_frame.text = notes


def bullet_paragraphs(tb, items, size, color=BLACK, number_color=CORAL, numbered=False, gap=8):
    tf = tb.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        p.line_spacing = 1.1
        _run(p, (f"{i + 1}.  " if numbered else "—  "), size, number_color, bold=numbered)
        _run(p, item, size, color)


# ============================================================== renderer
class DeckRenderer:
    def __init__(self, template: Path | None = None, uploaded_images: list[bytes] | None = None,
                 animations: bool = True):
        self.prs = Presentation(str(template or settings.template_path))
        self._strip_slides()
        self.layouts = {l.name: l for l in self.prs.slide_layouts}
        self.images = uploaded_images or []
        self.animations = animations
        self.section_no = 0
        self.section_title = ""

    def _strip_slides(self):
        lst = self.prs.slides._sldIdLst
        for sid in list(lst):
            self.prs.part.drop_rel(sid.rId)
            lst.remove(sid)

    def _new(self, kind: str):
        name = LAYOUTS[kind]
        layout = self.layouts.get(name) or self.prs.slide_layouts[0]
        return self.prs.slides.add_slide(layout)

    def _chrome(self, slide, kicker: str, dark=False):
        """Eyebrow label + slide number, as in the sample decks."""
        n = len(self.prs.slides)
        label = clamp_words((kicker or self.section_title or "").strip().rstrip("_").upper(), 4).rstrip("…")
        if label:
            tb = text_box(slide.shapes, MARGIN, 0.45, 9, 0.3, "", size=10)
            p = tb.text_frame.paragraphs[0]
            _run(p, label, 10, WHITE if dark else BLACK, spacing=300)
            _run(p, "_", 10, CORAL)
        text_box(slide.shapes, 12.2, 0.45, 0.63, 0.3, str(n), size=10, color=WHITE if dark else BLACK,
                 align=PP_ALIGN.RIGHT)

    def _finish(self, slide, notes="", animated=None, effect="fade"):
        remove_empty_placeholders(slide)
        set_notes(slide, notes)
        if self.animations:
            animate.add_fade_transition(slide)
            if animated:
                animate.add_staggered_entrance(slide, animated, effect=effect)

    # ------------------------------------------------------------------ entry
    def render(self, deck: DeckSpec) -> Presentation:
        for spec in deck.slides:
            fn = getattr(self, f"r_{spec.type}", None)
            if fn is None:
                log.warning("no renderer for %s", spec.type)
                continue
            try:
                fn(spec.content)
            except Exception:
                log.exception("render failed for %s; falling back to bullets", spec.type)
                c = spec.content
                self.r_bullets({"title": c.get("title", ""), "kicker": c.get("kicker", ""),
                                "bullets": _flatten_strings(c)[:5], "illustration": "none", "notes": c.get("notes", "")})
        self._new("end")
        return self.prs

    def save(self, path: Path):
        self.prs.save(str(path))

    # ------------------------------------------------------------------ slide types
    def r_cover(self, c):
        s = self._new("cover")
        set_bg(s, CREAM)
        sh = s.shapes
        # Decorative hands, same geometry as the sample covers.
        picture(sh, "hand/ok_pink", 3.29, -3.57, w=2.81, h=6.97, rot=121, flip_h=True)
        picture(sh, "hand/thumb_teal", 11.61, 0.81, w=2.98, h=6.97, rot=326)
        picture(sh, "hand/finger_red2", 6.7, 4.3, w=2.08, h=6.97, rot=19)
        title = clamp_words(c.get("title", ""), 10)
        size = fit_font_size([title], 7.3, 3.1, 60, 30, line_spacing=1.1, char_w=0.56)
        ph = set_title(s, title, size=size, underscore=True)
        if ph is not None:
            ph.left, ph.top, ph.width, ph.height = I(0.47), I(1.4), I(7.6), I(3.2)
            ph.text_frame.vertical_anchor = MSO_ANCHOR.BOTTOM
            ph._element.getparent().append(ph._element)  # title above decorations
        sub = clamp_words(c.get("subtitle", ""), 14)
        if sub and sub.strip().lower() != (c.get("date_line") or "").strip().lower():
            text_box(sh, MARGIN, 4.8, 6.9, 1.0, sub, size=20, color=BLACK, font=FONT_LIGHT)
        for ph in s.placeholders:
            if ph.placeholder_format.idx == 10:
                ph.text_frame.text = (c.get("date_line") or "").upper()
        self._finish(s)

    def r_agenda(self, c):
        s = self._new("content")
        set_title(s, c.get("title") or "Agenda")
        self._chrome(s, c.get("kicker", ""))
        rect(s.shapes, 8.7, 0, SLIDE_W - 8.7, SLIDE_H, fill=CREAM, rounded=0)
        picture(s.shapes, "sphere/coral", 9.6, 1.6, h=2.6)
        picture(s.shapes, "sphere/cream", 11.0, 4.2, h=1.8)
        items = c.get("items", [])[:6]
        row_h = min(0.8, (BODY_BOTTOM - BODY_TOP) / max(1, len(items)))
        animated = []
        for i, it in enumerate(items):
            y = BODY_TOP + i * row_h
            g = s.shapes.add_group_shape()
            text_box(g.shapes, MARGIN, y, 0.9, row_h, f"{i + 1:02d}", size=24, color=CORAL, font=FONT_LIGHT)
            text_box(g.shapes, 1.5, y, 6.9, row_h, clamp_words(it, 8), size=24, font=FONT_LIGHT)
            line(g.shapes, MARGIN, y + row_h - 0.12, 8.2, y + row_h - 0.12, color=LIGHT_GREY, width=0.75)
            animated.append(g)
        self._finish(s, c.get("notes", ""), animated)

    def r_section(self, c):
        self.section_no += 1
        self.section_title = c.get("title", "")
        s = self._new("section")
        set_bg(s, CREAM)
        sh = s.shapes
        orb = orbit(sh, 1.38, 1.40, 9.76, 5.11, 23)
        bar = rect(sh, 7.80, 2.17, 3.94, 0.59, fill=CORAL, rounded=0)
        bar.rotation = 345
        picture(sh, "sphere/cream", 5.35, 6.0, w=0.98, h=0.98)
        set_title(s, c.get("title", ""), size=54)
        for ph in s.placeholders:
            if ph.placeholder_format.idx == 12:
                ph.text_frame.text = f"{self.section_no:02d}"
        ttl = next((p for p in s.placeholders if p.placeholder_format.idx == 0), None)
        if ttl is not None:
            ttl._element.getparent().append(ttl._element)
        text_box(sh, 12.2, 0.45, 0.63, 0.3, str(len(self.prs.slides)), size=10, align=PP_ALIGN.RIGHT)
        self._finish(s, animated=[orb, bar], effect="wipe")

    def r_bullets(self, c):
        s = self._new("content")
        set_title(s, c.get("title", ""))
        self._chrome(s, c.get("kicker", ""))
        bullets = [clamp_words(b, 24) for b in c.get("bullets", [])][:6]
        illu = c.get("illustration", "none")
        if not illu or illu == "none" or asset(f"illustration/{illu}") is None:
            illu = pick_illustration(" ".join([c.get("title", ""), c.get("kicker", "")] + bullets))
        has_illu = asset(f"illustration/{illu}") is not None
        w = 6.6 if has_illu else 11.4
        if has_illu:
            rect(s.shapes, 7.7, 0, SLIDE_W - 7.7, SLIDE_H, fill=CREAM, rounded=0)
            pic = picture(s.shapes, f"illustration/{illu}", 8.2, 1.4, w=4.6)
            if pic is not None and pic.height > I(5.2):
                ratio = I(5.2) / pic.height
                pic.height, pic.width = I(5.2), int(pic.width * ratio)
        size = fit_font_size(bullets, w - 0.5, BODY_BOTTOM - BODY_TOP - 0.2, 26 if len(bullets) <= 3 else 22, 12,
                             line_spacing=1.2)
        tb = text_box(s.shapes, MARGIN, BODY_TOP, w, BODY_BOTTOM - BODY_TOP)
        bullet_paragraphs(tb, bullets, size, numbered=True, gap=14 if len(bullets) <= 4 else 8)
        self._finish(s, c.get("notes", ""), [tb])

    def r_kpis(self, c):
        s = self._new("content")
        set_bg(s, CREAM)
        set_title(s, c.get("title", ""))
        self._chrome(s, c.get("kicker", ""))
        kpis = c.get("kpis", [])[:4]
        n = max(1, len(kpis))
        gap = 0.3
        card_w = (SLIDE_W - 2 * MARGIN - gap * (n - 1)) / n
        card_h = 3.1
        animated = []
        for i, k in enumerate(kpis):
            x = MARGIN + i * (card_w + gap)
            g = s.shapes.add_group_shape()
            rect(g.shapes, x, BODY_TOP, card_w, card_h, fill=CREAM_LIGHT, rounded=0.05)
            color = {"positive": TEAL_TEXT, "negative": CORAL}.get(k.get("sentiment"), GREEN)
            val = str(k.get("value", ""))[:9]
            vsize = min(60, fit_font_size([val], card_w - 0.6, 1.1, 60, 28, char_w=0.55, line_spacing=1.0))
            text_box(g.shapes, x + 0.35, BODY_TOP + 0.35, card_w - 0.6, 1.1, val, size=vsize, color=color,
                     font=FONT_HEAD)
            label = clamp_words(k.get("label", ""), 8)
            text_box(g.shapes, x + 0.35, BODY_TOP + 1.55, card_w - 0.6, 0.7, label,
                     size=fit_font_size([label], card_w - 0.6, 0.7, 16, 11), font=FONT_HEAD)
            if k.get("context"):
                text_box(g.shapes, x + 0.35, BODY_TOP + 2.3, card_w - 0.6, 0.6, clamp_words(k["context"], 10),
                         size=12, color=GREY, font=FONT_LIGHT)
            animated.append(g)
        take = c.get("takeaway", "")
        if take:
            g = s.shapes.add_group_shape()
            rect(g.shapes, MARGIN, BODY_TOP + card_h + 0.35, 0.08, 1.0, fill=CORAL, rounded=0)
            text_box(g.shapes, MARGIN + 0.3, BODY_TOP + card_h + 0.35, SLIDE_W - 2 * MARGIN - 0.3, 1.1,
                     clamp_words(take, 32), size=18, font=FONT_LIGHT, anchor=MSO_ANCHOR.MIDDLE)
            animated.append(g)
        self._finish(s, c.get("notes", ""), animated)

    def r_chart(self, c):
        s = self._new("content")
        set_title(s, c.get("title", ""))
        self._chrome(s, c.get("kicker", ""))
        cats = [clamp_words(str(x), 6) for x in c.get("categories", [])][:12]
        series = c.get("series", [])[:3]
        ctype = c.get("chart_type", "column")
        unit = (c.get("unit") or "").strip()
        if len(unit) > 3 or unit.isalpha() and unit.lower() not in ("k", "m", "bn", "pp", "pts"):
            unit = ""  # words like "score" or "employees" belong in the title, not on every label
        if not cats or not series:
            return self.r_bullets({**c, "bullets": c.get("takeaways", []), "illustration": "documents"})
        if ctype == "column" and sum(len(x) for x in cats) / len(cats) > 12:
            ctype = "bar"  # long labels read better horizontally
        if ctype in ("pie", "doughnut"):
            series = series[:1]

        cd = CategoryChartData()
        cd.categories = cats
        all_vals = []
        clean = []
        for ser in series:
            vals = [float(v) if v is not None else 0.0 for v in (ser.get("values") or [])]
            vals = (vals + [0.0] * len(cats))[: len(cats)]
            clean.append((clamp_words(ser.get("name", "") or "Value", 5), vals))
            all_vals += vals
        decimals = 0 if all(abs(v - round(v)) < 1e-9 for v in all_vals) else (
            1 if all(abs(v * 10 - round(v * 10)) < 1e-6 for v in all_vals) else 2)
        base = "#,##0" + ("." + "0" * decimals if decimals else "")
        fmt = base + ('"%"' if unit == "%" else (f'" {unit}"' if unit else ""))
        for name, vals in clean:
            cd.add_series(name, vals, number_format=fmt)

        xl = {
            "bar": XL_CHART_TYPE.BAR_CLUSTERED, "column": XL_CHART_TYPE.COLUMN_CLUSTERED,
            "line": XL_CHART_TYPE.LINE_MARKERS, "pie": XL_CHART_TYPE.PIE, "doughnut": XL_CHART_TYPE.DOUGHNUT,
            "stacked_bar": XL_CHART_TYPE.BAR_STACKED,
        }.get(ctype, XL_CHART_TYPE.COLUMN_CLUSTERED)
        cw = 8.2
        gf = s.shapes.add_chart(xl, I(MARGIN), I(BODY_TOP), I(cw), I(BODY_BOTTOM - BODY_TOP), cd)
        style_chart(gf.chart, ctype, len(clean), len(cats))
        if ctype == "line" and len(clean) > 1:
            label_line_ends(gf.chart, clean, fmt)

        takeaways = [clamp_words(t, 22) for t in c.get("takeaways", [])][:3]
        g = s.shapes.add_group_shape()
        px = MARGIN + cw + 0.4
        pw = SLIDE_W - MARGIN - px
        rect(g.shapes, px, BODY_TOP, pw, BODY_BOTTOM - BODY_TOP, fill=CREAM_LIGHT, rounded=0.04)
        text_box(g.shapes, px + 0.3, BODY_TOP + 0.3, pw - 0.6, 0.35, "", size=11)
        hdr = g.shapes[-1].text_frame.paragraphs[0]
        _run(hdr, "KEY TAKEAWAYS", 11, BLACK, spacing=250)
        _run(hdr, "_", 11, CORAL)
        size = fit_font_size(takeaways, pw - 0.6, BODY_BOTTOM - BODY_TOP - 1.1, 16, 11)
        tb = text_box(g.shapes, px + 0.3, BODY_TOP + 0.9, pw - 0.6, BODY_BOTTOM - BODY_TOP - 1.1)
        bullet_paragraphs(tb, takeaways, size, gap=12)
        self._finish(s, c.get("notes", ""), [gf, g])

    def r_cards(self, c):
        s = self._new("content")
        set_bg(s, CREAM)
        set_title(s, c.get("title", ""))
        self._chrome(s, c.get("kicker", ""))
        cards = c.get("cards", [])[:4]
        n = max(1, len(cards))
        gap = 0.3
        w = (SLIDE_W - 2 * MARGIN - gap * (n - 1)) / n
        h = BODY_BOTTOM - BODY_TOP
        texts = [clamp_words(cd.get("text", ""), 26) for cd in cards]
        tsize = fit_uniform(texts, w - 0.6, h - 2.8, 17, 10)
        icons = distinct_icons([(cd.get("icon", ""), f"{cd.get('heading', '')} {cd.get('text', '')}") for cd in cards])
        animated = []
        for i, cd in enumerate(cards):
            cd = {**cd, "icon": icons[i]}
            x = MARGIN + i * (w + gap)
            g = s.shapes.add_group_shape()
            rect(g.shapes, x, BODY_TOP, w, h, fill=CREAM_LIGHT, rounded=0.05)
            circ = rect(g.shapes, x + 0.35, BODY_TOP + 0.35, 1.1, 1.1, fill=WHITE, shape=MSO_SHAPE.OVAL, rounded=0)
            circ.line.color.rgb = rgb(LIGHT_GREY)
            circ.line.width = Pt(0.75)
            picture(g.shapes, f"icon/{cd.get('icon', 'lightbulb')}", x + 0.5, BODY_TOP + 0.5, w=0.8)
            text_box(g.shapes, x + 0.35, BODY_TOP + 1.75, w - 0.6, 0.75, clamp_words(cd.get("heading", ""), 5),
                     size=19, font=FONT_HEAD)
            text_box(g.shapes, x + 0.35, BODY_TOP + 2.55, w - 0.6, h - 2.8, texts[i], size=tsize, font=FONT_LIGHT,
                     line_spacing=1.15)
            animated.append(g)
        self._finish(s, c.get("notes", ""), animated)

    def r_process(self, c):
        s = self._new("content")
        set_title(s, c.get("title", ""))
        self._chrome(s, c.get("kicker", ""))
        steps = [dict(st) for st in c.get("steps", [])[:6]]
        for st in steps:
            if GENERIC_LABEL.match(st.get("label", "")):
                text = st.get("text", "")
                st["label"], st["text"] = (text, "") if len(text.split()) <= 6 else ("", text)
        n = max(1, len(steps))
