def style_chart(chart, ctype: str, n_series: int, n_cats: int):
    chart.font.size = Pt(11)
    chart.font.color.rgb = rgb(GREY)
    chart.has_title = False
    plot = chart.plots[0]
    if ctype in ("pie", "doughnut"):
        chart.has_legend = True
        chart.legend.position = XL_LEGEND_POSITION.RIGHT
        chart.legend.include_in_layout = False
        chart.legend.font.size = Pt(12)
        ser = plot.series[0]
        for i, pt in enumerate(ser.points):
            pt.format.fill.solid()
            pt.format.fill.fore_color.rgb = rgb(SERIES_COLORS[i % len(SERIES_COLORS)])
            pt.format.line.color.rgb = rgb(WHITE)
        plot.has_data_labels = True
        dl = plot.data_labels
        dl.font.size = Pt(12)
        dl.font.color.rgb = rgb(BLACK)
        if ctype == "doughnut":
            hole = plot._element.find(qn("c:holeSize"))
            if hole is not None:
                hole.set("val", "62")
        return

    chart.has_legend = n_series > 1
    if chart.has_legend:
        chart.legend.position = XL_LEGEND_POSITION.TOP
        chart.legend.include_in_layout = False
        chart.legend.font.size = Pt(11)
    for i, ser in enumerate(plot.series):
        color = rgb(SERIES_COLORS[i % len(SERIES_COLORS)])
        if ctype == "line":
            ser.format.line.color.rgb = color
            ser.format.line.width = Pt(2.5)
            ser.smooth = False
            ser.marker.format.fill.solid()
            ser.marker.format.fill.fore_color.rgb = color
            ser.marker.format.line.color.rgb = rgb(WHITE)
            ser.marker.size = 8
        else:
            ser.format.fill.solid()
            ser.format.fill.fore_color.rgb = color
            ser.format.line.fill.background()
    if ctype != "line":
        try:
            plot.gap_width = 60 if n_cats > 4 else 90
            plot.overlap = 100 if ctype == "stacked_bar" else (-10 if n_series > 1 else 0)
        except Exception:
            pass
    plot.has_data_labels = True
    dl = plot.data_labels
    dl.font.size = Pt(11)
    dl.font.color.rgb = rgb(BLACK)
    if ctype in ("bar", "column"):
        dl.position = XL_LABEL_POSITION.OUTSIDE_END
    elif ctype == "line":
        dl.position = XL_LABEL_POSITION.ABOVE
    va = chart.value_axis
    va.has_major_gridlines = False
    va.visible = False
    va.tick_labels.font.size = Pt(10)
    ca = chart.category_axis
    ca.tick_label_position = XL_TICK_LABEL_POSITION.LOW  # labels stay at the bottom even with negative values
    ca.tick_labels.font.size = Pt(11 if n_cats <= 6 else 9)
    ca.format.line.color.rgb = rgb(LIGHT_GREY)
    ca.has_major_gridlines = False
    if ctype in ("bar", "stacked_bar"):
        ca.reverse_order = True  # first category on top, like the sample decks
        # reverse_order moves the value axis to the top; keep it visually clean.
        va.visible = False


def label_line_ends(chart, series: list[tuple[str, list[float]]], fmt: str):
    """Multi-series lines: label only the last point of each series (name + value) to avoid label pile-ups."""
    plot = chart.plots[0]
    plot.has_data_labels = False
    decimals = len(fmt.split(".")[1].split('"')[0]) if "." in fmt else 0
    suffix = "%" if '"%"' in fmt else ""
    for ser, (name, vals) in zip(plot.series, series):
        if not vals:
            continue
        dl = ser.points[len(vals) - 1].data_label
        dl.position = XL_LABEL_POSITION.RIGHT
        tf = dl.text_frame
        tf.text = f"{vals[-1]:.{decimals}f}{suffix}"
        for r in tf.paragraphs[0].runs:
            r.font.size = Pt(12)
            r.font.bold = True
            r.font.color.rgb = rgb(BLACK)


_BORDER_ORDER = ["a:lnL", "a:lnR", "a:lnT", "a:lnB"]


def _cell_borders(cell, borders: dict[str, tuple[str, float]]):
    """borders: {'lnT': (color or '', width_pt), ...}. Schema requires lnL,lnR,lnT,lnB before the cell fill."""
    tcPr = cell._tc.get_or_add_tcPr()
    for tag in _BORDER_ORDER:
        for old in tcPr.findall(qn(tag)):
            tcPr.remove(old)
    for pos, tag in enumerate(_BORDER_ORDER):
        color, width_pt = borders.get(tag[2:], ("", 0))
        ln = etree.Element(qn(tag), w=str(int(width_pt * 12700)), cap="flat", cmpd="sng", algn="ctr")
        if color:
            sf = etree.SubElement(ln, qn("a:solidFill"))
            etree.SubElement(sf, qn("a:srgbClr"), val=color)
        else:
            etree.SubElement(ln, qn("a:noFill"))
        tcPr.insert(pos, ln)


def style_table(gf, cols, rows):
    tbl = gf.table
    # "No Style, No Grid"
    tbl._tbl.tblPr.find(qn("a:tableStyleId")).text = "{2D5ABB26-0587-4C30-8999-92F81FD0307C}"
    tbl.first_row = True
    numeric = [all(_is_num(r[j]) for r in rows if r[j]) and any(r[j] for r in rows) for j in range(len(cols))]
    first_w = 0.34 if len(cols) > 2 else 0.5
    total = SLIDE_W - 2 * MARGIN
    tbl.columns[0].width = I(total * first_w)
    for j in range(1, len(cols)):
        tbl.columns[j].width = I(total * (1 - first_w) / (len(cols) - 1))
    for i in range(len(rows) + 1):
        for j in range(len(cols)):
            cell = tbl.cell(i, j)
            cell.fill.background()
            cell.margin_left = cell.margin_right = I(0.1)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.RIGHT if (numeric[j] and j > 0) else PP_ALIGN.LEFT
            if i == 0:
                _run(p, cols[j].upper(), 10, BLACK, spacing=200)
                _cell_borders(cell, {"lnT": (BLACK, 2), "lnB": (BLACK, 0.75)})
            else:
                val = rows[i - 1][j]
                color = BLACK
                if val.strip().startswith(("▲", "+")) and numeric[j]:
                    color = TEAL_TEXT
                elif val.strip().startswith(("▼", "-", "−")) and numeric[j]:
                    color = CORAL
                _run(p, val, 13 if j == 0 else 14, color, font=FONT_LIGHT if j == 0 else FONT_HEAD)
                _cell_borders(cell, {"lnT": (LIGHT_GREY if i > 1 else BLACK, 0.75), "lnB": (LIGHT_GREY, 0.75)})


def _is_num(s: str) -> bool:
    t = s.replace("%", "").replace(",", ".").replace(" ", "").replace("▲", "").replace("▼", "").replace("€", "") \
        .replace("$", "").replace("+", "").replace("−", "-").strip()
    try:
        float(t)
        return True
    except ValueError:
        return False


def _flatten_strings(obj) -> list[str]:
    out = []
    if isinstance(obj, str):
        if obj.strip():
            out.append(obj)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if k not in ("notes", "kicker", "title", "icon", "illustration", "chart_type", "unit"):
                out.extend(_flatten_strings(v))
    elif isinstance(obj, list):
        for v in obj:
            out.extend(_flatten_strings(v))
    return out


